// Attendance (recomputeDay/resolveExpectedShift) always reads an employee's
// CURRENT position/defaultShiftCategory live, at the moment each scan comes
// in — there's no snapshot. That's a problem specifically on the swap's own
// effective date: the Employee fields below flip the moment this function
// runs, but that could land anywhere from midnight to ~15 minutes later (see
// index.js's recurring check) or instantly if an admin happens to open the
// swap list page — so a scan arriving right at shift-start on that exact day
// could get evaluated against whichever side of the flip it happens to race.
// Pinning a 'scheduled' Shift override for that one date removes the race
// entirely: resolveExpectedShift checks for a same-date Shift override
// FIRST, before ever falling back to the live position/category, so the old
// schedule governs the whole transition day no matter when the flip lands.
// This is the general/fallback treatment — pins each mover's own unchanged
// old shift for one day. Used whenever the two positions' old shifts don't
// cleanly tile a 24-hour day (see applyPositionSwap); the real ກະເຊົ້າ/ກະແລງ
// pattern gets the more specific extend/blank treatment right below instead.
// Skipped if the employee already has any Shift for that date that an admin
// set by hand (their explicit choice for that specific day wins over this
// automatic one) — but not skipped for a pin this same mechanism created
// earlier (see isAutoGeneratedSwapPin), so swapping the same two positions
// back on the same day re-derives today correctly instead of leaving a
// stale pin from the first swap behind. Also skipped for someone who had no
// shift time to snapshot in the first place.
const AUTO_SWAP_PIN_NOTE_PREFIX = 'ສ້າງອັດຕະໂນມັດ';
// What each automatic swap-day pin says — also how ສະຫຼັບກະ tells what the swap
// did on its date (describeSwapPeople).
const SWAP_PIN_NOTES = {
  kept: 'ສ້າງອັດຕະໂນມັດ — ຮັກສາຕາຕະລາງເກົ່າໄວ້ໃນມື້ສະຫຼັບຕຳແໜ່ງ',
  extended: 'ສ້າງອັດຕະໂນມັດ — ເຮັດວຽກຕໍ່ເນື່ອງຍາວໃນມື້ສະຫຼັບຕຳແໜ່ງ',
  off: 'ສ້າງອັດຕະໂນມັດ — ບໍ່ມີກະໃນມື້ສະຫຼັບຕຳແໜ່ງ',
};
function isAutoGeneratedSwapPin(shift) {
  return typeof shift.note === 'string' && shift.note.startsWith(AUTO_SWAP_PIN_NOTE_PREFIX);
}
async function clearAutoPinIfAny(employeeId, effectiveDate) {
  const existing = await Shift.findOne({ employee: employeeId, date: effectiveDate });
  if (!existing) return true;
  if (!isAutoGeneratedSwapPin(existing)) return false;
  await Shift.deleteOne({ _id: existing._id });
  return true;
}

async function pinOldScheduleForSwapDay(employee, oldPositionId, effectiveDate) {
  const hasCategory = !!employee.defaultShiftCategory;
  if (!hasCategory && !(employee.defaultShiftStart && employee.defaultShiftEnd)) return;
  if (!(await clearAutoPinIfAny(employee._id, effectiveDate))) return;
  let startTime = employee.defaultShiftStart;
  let endTime = employee.defaultShiftEnd;
  if (hasCategory) {
    const category = await ShiftCategory.findById(employee.defaultShiftCategory);
    if (!category) return;
    startTime = category.startTime;
    endTime = category.endTime;
  }
  await Shift.create({
    employee: employee._id,
    position: oldPositionId,
    category: hasCategory ? employee.defaultShiftCategory : undefined,
    date: effectiveDate,
    status: 'scheduled',
    startTime,
    endTime,
    note: SWAP_PIN_NOTES.kept,
  });
}

// Resolves a concrete {startTime, endTime} for whichever employee
// canonicalTimeOf() read the group's time from (fetching the category if
// that's how it was set) — needed to compare the two positions' old shift
// times and decide which swap-day treatment applies. Null when there's
// nothing to resolve (empty position, or a category that's been deleted).
async function resolveCanonicalTime(canonical) {
  if (canonical.categoryId) {
    const category = await ShiftCategory.findById(canonical.categoryId);
    return category ? { startTime: category.startTime, endTime: category.endTime } : null;
  }
  if (canonical.start && canonical.end) return { startTime: canonical.start, endTime: canonical.end };
  return null;
}

// One minute before `time` (HH:mm). isOvernightShift only compares hour and
// minute, with no cap on how long an "overnight" shift can run — so an
// override whose endTime is a single minute earlier than its startTime reads
// as running the full next calendar day through to just before that same
// clock time again, which is exactly the "one continuous ~24h shift" the
// early-leaving group below needs, without touching that shared comparison.
function oneMinuteBefore(time) {
  const [h, m] = time.split(':').map(Number);
  const total = (h * 60 + m - 1 + 24 * 60) % (24 * 60);
  return `${String(Math.floor(total / 60)).padStart(2, '0')}:${String(total % 60).padStart(2, '0')}`;
}

// The ກະເຊົ້າ/ກະແລງ pattern: the two positions' old shifts exactly tile a
// 24-hour day (e.g. 06:00-18:00 and 18:00-06:00). Calling back someone who
// already went home for one more rotation is worse than having whoever's
// already on site work straight through — so on the swap day, the group
// leaving the EARLIER-starting shift works one continuous ~24h shift
// covering both halves of the day (pinExtendedScheduleForSwapDay), and the
// group leaving the LATER-starting shift has nothing scheduled that day at
// all (pinBlankScheduleForSwapDay) — their last real occurrence already
// ended earlier that same morning, and their first new-schedule shift starts
// clean the day after. Both skip an employee who already has a Shift that
// date, same as the general case above.
async function pinExtendedScheduleForSwapDay(employee, oldPositionId, startTime, lateEnd, categoryId, effectiveDate) {
  if (!(await clearAutoPinIfAny(employee._id, effectiveDate))) return;
  // Normally ends exactly where the late shift itself ends (e.g. 06:00) —
  // that's what "cover through the handover point" actually means. Only
  // falls back to the one-minute-before trick when the two shifts tile with
  // zero gap, where lateEnd === startTime would otherwise look like a
  // zero-length shift to isOvernightShift instead of a ~24h one.
  const endTime = lateEnd === startTime ? oneMinuteBefore(startTime) : lateEnd;
  await Shift.create({
    employee: employee._id,
    position: oldPositionId,
    // Without this, resolveExpectedShift's grace/severeLate/autoAbsent policy
    // for this one day silently falls back to the hardcoded module defaults
    // instead of whatever the old category actually has configured — carrying
    // it over keeps the day's late/absent labels consistent with every other
    // day this group worked that shift.
    category: categoryId ?? undefined,
    date: effectiveDate,
    status: 'scheduled',
    startTime,
    endTime,
    note: SWAP_PIN_NOTES.extended,
  });
}

async function pinBlankScheduleForSwapDay(employee, effectiveDate) {
  if (!(await clearAutoPinIfAny(employee._id, effectiveDate))) return;
  await Shift.create({
    employee: employee._id,
    date: effectiveDate,
    status: 'swapped',
    note: SWAP_PIN_NOTES.off,
  });
}

// A mover's own rest day carries over unchanged unless their NEW position
// forbids it, in which case it's redirected to that position's configured
// fallback right here — the same rule employees.js/shifts.js apply when
// someone picks a rest day by hand, just applied automatically since nobody
// is sitting at a form during a swap. The change is recorded as of the swap
// date (restDaySchedule.js), so days before it keep the old rest day. A
// change already planned for after the swap (ວາງແຜນວັນພັກ) was checked
// against the old position, so it's checked again against the new one the
// same way. A day that IS forbidden but has no fallback configured is left
// as-is, same gap as before this existed, since there's no admin to ask
// mid-swap. Returns whether anything changed, and the rest day on the swap
// date before and after it.
function restDayAllowedIn(employee, newPosition) {
  const rule = mergeRestDayRule(employee, newPosition);
  return (days) => {
    try {
      return resolveRestDayForPosition(rule, days);
    } catch {
      return days;
    }
  };
}
async function resolveMoverRestDay(employee, newPosition, effectiveDate) {
  const allowed = restDayAllowedIn(employee, newPosition);
  const record = (newRestDay, date) =>
    recordRestDayChange({
      employeeId: employee._id,
      newRestDay,
      effectiveDate: date,
      source: 'position-swap',
      changedByEmail: 'ລະບົບ (ສະຫຼັບຕຳແໜ່ງອັດຕະໂນມັດ)',
    });
  let changed = false;
  const current = await restDaysOnFor(employee._id, effectiveDate);
  let after = current;
  if (current.length && !sameRestDays(allowed(current), current)) {
    after = allowed(current);
    await record(after, effectiveDate);
    changed = true;
  }
  const planned = await RestDayHistory.find({ employee: employee._id, effectiveDate: { $gt: effectiveDate } }).sort({ effectiveDate: 1 }).lean();
  for (const row of planned) {
    if (sameRestDays(allowed(row.newRestDay), row.newRestDay)) continue;
    // eslint-disable-next-line no-await-in-loop
    await record(allowed(row.newRestDay), row.effectiveDate);
    changed = true;
  }
  return { changed, before: current, after };
}

// Whoever currently holds a position all shares one working time (see the
// KTV server positions this was built for) — so swapping isn't a 1-to-1
// person pairing, it's "everyone in A moves to B and takes on B's time, and
// vice versa." The canonical time for a position is read off its first
// current member (sorted by employee code); an empty position has no time to
// hand out, so movers into it end up with no default shift set.
function canonicalTimeOf(list) {
  const ref = list[0];
  return {
    categoryId: ref?.defaultShiftCategory ?? null,
    start: ref && !ref.defaultShiftCategory ? ref.defaultShiftStart ?? null : null,
    end: ref && !ref.defaultShiftCategory ? ref.defaultShiftEnd ?? null : null,
  };
}

// Real shift pairs usually don't tile exactly — a handover/cleaning gap
// between one ending and the other starting (e.g. evening ends 06:00,
// morning starts 07:00) is normal, not a sign these are unrelated shifts.
// So this checks "sequential with no overlap" (each one's end at or
// before the other's start) rather than requiring the boundaries to land
// on the exact same minute.
function tilesFullDay(oldTimeA, oldTimeB) {
  const toMinutes = (hhmm) => {
    const [h, m] = hhmm.split(':').map(Number);
    return h * 60 + m;
  };
  return (
    !!oldTimeA &&
    !!oldTimeB &&
    toMinutes(oldTimeA.endTime) <= toMinutes(oldTimeB.startTime) &&
    toMinutes(oldTimeB.endTime) <= toMinutes(oldTimeA.startTime)
  );
}

// Resolves each position's CURRENT membership at the moment this runs (not
// whatever it was when the swap was scheduled) and swaps them. This is what
// makes "schedule for next month" safe — anyone hired, moved, or resigned
// between now and the effective date is still handled correctly because
// membership is looked up fresh every time this actually executes.
async function applyPositionSwap(positionAId, positionBId, effectiveDate) {
  const [positionA, positionB, empListA, empListB] = await Promise.all([
    Position.findById(positionAId),
    Position.findById(positionBId),
    Employee.find({ position: positionAId, status: 'active' }).sort('employeeCode'),
    Employee.find({ position: positionBId, status: 'active' }).sort('employeeCode'),
  ]);

  const canonicalA = canonicalTimeOf(empListA);
  const canonicalB = canonicalTimeOf(empListB);

  if (effectiveDate) {
    const [oldTimeA, oldTimeB] = await Promise.all([resolveCanonicalTime(canonicalA), resolveCanonicalTime(canonicalB)]);
    if (tilesFullDay(oldTimeA, oldTimeB)) {
      const aIsEarly = oldTimeA.startTime < oldTimeB.startTime;
      const earlyList = aIsEarly ? empListA : empListB;
      const earlyOldPositionId = aIsEarly ? positionAId : positionBId;
      const earlyStart = aIsEarly ? oldTimeA.startTime : oldTimeB.startTime;
      const earlyCategoryId = aIsEarly ? canonicalA.categoryId : canonicalB.categoryId;
      // The late shift's own end (e.g. 06:00), not "24h after the early
      // shift's start" — with a handover gap the two aren't the same instant,
      // and the whole point is covering through to where the late shift
      // itself would have ended.
      const lateEnd = aIsEarly ? oldTimeB.endTime : oldTimeA.endTime;
      const lateList = aIsEarly ? empListB : empListA;
      await Promise.all([
        ...earlyList.map((e) => pinExtendedScheduleForSwapDay(e, earlyOldPositionId, earlyStart, lateEnd, earlyCategoryId, effectiveDate)),
        ...lateList.map((e) => pinBlankScheduleForSwapDay(e, effectiveDate)),
      ]);
    } else {
      await Promise.all([
        ...empListA.map((e) => pinOldScheduleForSwapDay(e, positionAId, effectiveDate)),
        ...empListB.map((e) => pinOldScheduleForSwapDay(e, positionBId, effectiveDate)),
      ]);
    }
  }

  const historyDate = effectiveDate || toDateKey(new Date());
  const [restDayA, restDayB] = await Promise.all([
    Promise.all(empListA.map((e) => resolveMoverRestDay(e, positionB, historyDate))),
    Promise.all(empListB.map((e) => resolveMoverRestDay(e, positionA, historyDate))),
  ]);

  // The designated head travels with the group, same as their shift time —
  // whoever led position A now leads wherever that group ended up (B), and
  // vice versa. So each mover keeps pointing at THEIR OWN old position's head
  // (positionA?.head for A-movers, positionB?.head for B-movers) rather than
  // picking up the other side's, and the positions' own `head` fields swap to
  // match so a later admin look-up of "who heads this position" agrees with it.
  await Promise.all([
    ...empListA.map((e) =>
      Employee.updateOne(
        { _id: e._id },
        {
          position: positionBId,
          positionHead: positionA?.head || null,
          defaultShiftCategory: canonicalB.categoryId,
          defaultShiftStart: canonicalB.start,
          defaultShiftEnd: canonicalB.end,
        }
      )
    ),
    ...empListB.map((e) =>
      Employee.updateOne(
        { _id: e._id },
        {
          position: positionAId,
          positionHead: positionB?.head || null,
          defaultShiftCategory: canonicalA.categoryId,
          defaultShiftStart: canonicalA.start,
          defaultShiftEnd: canonicalA.end,
        }
      )
    ),
    Position.updateOne({ _id: positionAId }, { head: positionB?.head || null }),
    Position.updateOne({ _id: positionBId }, { head: positionA?.head || null }),
  ]);

  // A mover whose rest day just moved has their leaves from the swap date on
  // worked out again against it (utils/leaveDeduction.js).
  const restMoved = [...empListA.filter((_, i) => restDayA[i].changed), ...empListB.filter((_, i) => restDayB[i].changed)];
  for (const e of restMoved) {
    // eslint-disable-next-line no-await-in-loop
    await recomputeLeavesAfterRestChange(e._id, historyDate);
  }

  // Recorded as of the swap date, so every day before it keeps being judged
  // by each mover's old shift — without this, the night group's last night
  // would be re-read as a day shift and its morning scan-out would land on
  // the swap day instead (see models/ShiftChangeLog.js).
  const toB ={ defaultShiftCategory: canonicalB.categoryId, defaultShiftStart: canonicalB.start, defaultShiftEnd: canonicalB.end };
  const toA = { defaultShiftCategory: canonicalA.categoryId, defaultShiftStart: canonicalA.start, defaultShiftEnd: canonicalA.end };
  await Promise.all([
    ...empListA.map((e) => recordShiftChange(e._id, e, toB, historyDate, 'position-swap')),
    ...empListB.map((e) => recordShiftChange(e._id, e, toA, historyDate, 'position-swap')),
  ]);

  // What each one's swap was, kept on the swap so ສະຫຼັບກະ can show it later.
  const [nextForA, nextForB] = await Promise.all([snapshotShift(toB), snapshotShift(toA)]);
  const basic = [
    ...empListA.map((e, i) => ({ employee: e._id, from: 'A', next: nextForA, restDay: { before: restDayA[i].before, after: restDayA[i].after } })),
    ...empListB.map((e, i) => ({ employee: e._id, from: 'B', next: nextForB, restDay: { before: restDayB[i].before, after: restDayB[i].after } })),
  ];
  const previous = await Promise.all([...empListA, ...empListB].map((e) => snapshotShift(e)));
  const movers = await describeSwapPeople(
    historyDate,
    basic.map((m, i) => ({ ...m, previous: previous[i] }))
  );

  return {
    movedFromA: empListA.length,
    movedFromB: empListB.length,
    movers,
  };
}

function swapDayOf(shift) {
  if (!shift) return undefined;
  const kind = Object.keys(SWAP_PIN_NOTES).find((k) => SWAP_PIN_NOTES[k] === shift.note) ?? 'set';
  return { kind, status: shift.status, startTime: shift.startTime ?? null, endTime: shift.endTime ?? null };
}

// Each mover's swap: their regular shift before and after, what they had on the
// swap date itself, and their rest day before and after it. Whatever a mover
// already carries is kept; the rest is read off what the swap left behind that
// day — so it's only complete while the swap is still in place (ຍ້ອນກັບ removes
// those, which is why revertPositionSwap stores this first).
async function describeSwapPeople(date, movers) {
  if (!movers.length) return [];
  const ids = movers.map((m) => m.employee);
  const [logs, shifts, rests] = await Promise.all([
    ShiftChangeLog.find({ employee: { $in: ids }, effectiveDate: date }).lean(),
    Shift.find({ employee: { $in: ids }, date }).lean(),
    RestDayHistory.find({ employee: { $in: ids }, effectiveDate: date, source: 'position-swap' }).lean(),
  ]);
  const byEmployee = (rows) => new Map(rows.map((r) => [String(r.employee), r]));
  const logOf = byEmployee(logs);
  const shiftOf = byEmployee(shifts);
  const restOf = byEmployee(rests);
  const snapshot = (s) => (s ? { category: s.category ?? null, startTime: s.startTime ?? null, endTime: s.endTime ?? null } : undefined);
  return movers.map((m) => {
    const plain = typeof m.toObject === 'function' ? m.toObject() : m;
    const id = String(plain.employee);
    const log = logOf.get(id);
    const rest = restOf.get(id);
    return {
      employee: plain.employee,
      from: plain.from,
      previous: plain.previous ?? snapshot(log?.previous),
      next: plain.next ?? snapshot(log?.next),
      swapDay: plain.swapDay ?? swapDayOf(shiftOf.get(id)),
      restDay: plain.restDay ?? (rest ? { before: rest.previousRestDay ?? [], after: rest.newRestDay ?? [] } : undefined),
    };
  });
}

const SWAP_REST_DAY_EMAIL = 'ລະບົບ (ສະຫຼັບຕຳແໜ່ງອັດຕະໂນມັດ)';

// A swap applied before its movers were recorded: whoever it left a trace on
// that day — an automatic pin, a regular-shift change or a rest-day change of
// its own — and is still in one of the two positions. Which side they came from
// follows from where they are now.
async function findMoversOf(swap) {
  const date = swap.effectiveDate;
  const [pins, logs, rests] = await Promise.all([
    Shift.find({ date, note: { $regex: `^${AUTO_SWAP_PIN_NOTE_PREFIX}` } }, 'employee'),
    ShiftChangeLog.find({ effectiveDate: date, source: 'position-swap' }, 'employee'),
    RestDayHistory.find({ effectiveDate: date, source: 'position-swap' }, 'employee'),
  ]);
  // Someone another recorded swap that day moved belongs to that one.
  const others = await ScheduledPositionSwap.find({ _id: { $ne: swap._id }, effectiveDate: date, status: { $in: ['applied', 'reverted'] } }, 'movers');
  const theirs = new Set(others.flatMap((o) => (o.movers ?? []).map((m) => String(m.employee))));
  const ids = [...new Set([...pins, ...logs, ...rests].map((r) => String(r.employee)))].filter((id) => !theirs.has(id));
  const employees = await Employee.find({ _id: { $in: ids }, position: { $in: [swap.positionA, swap.positionB] } }, 'position');
  return employees.map((e) => ({ employee: e._id, from: String(e.position) === String(swap.positionB) ? 'A' : 'B' }));
}

// Swaps whose record was deleted from ສະຫຼັບກະ's history while their changes
// are still in place, so they can be put back on the list and undone: each day
// with a swap's traces (automatic pins, regular-shift or rest-day changes it
// made) left on people no recorded swap that day accounts for — not one of its
// movers, not in one of its positions now. The pair comes first from the day's
// pins, which keep the position each person was moved out of: that and where
// they are now. With none to go by, it's the two positions most of them are in
// now. When two pairs are equally likely (someone moved again since), it's
// marked ambiguous and never put back on a guess: undoing the wrong pair would
// move the wrong people.
async function findUnrecordedSwaps() {
  const [pins, logs, rests, records] = await Promise.all([
    Shift.find({ note: { $regex: `^${AUTO_SWAP_PIN_NOTE_PREFIX}` } }, 'employee date position createdAt'),
    ShiftChangeLog.find({ source: 'position-swap' }, 'employee effectiveDate createdAt'),
    RestDayHistory.find({ source: 'position-swap', changedByEmail: SWAP_REST_DAY_EMAIL }, 'employee effectiveDate createdAt'),
    ScheduledPositionSwap.find({ status: { $in: ['applied', 'reverted'] } }, 'positionA positionB effectiveDate movers'),
  ]);
  const byDate = new Map();
  const add = (date, employee, at) => {
    if (!date || !employee) return;
    const entry = byDate.get(date) ?? { employees: new Set(), pins: [], firstAt: at };
    entry.employees.add(String(employee));
    if (at && (!entry.firstAt || at < entry.firstAt)) entry.firstAt = at;
    byDate.set(date, entry);
  };
  for (const p of pins) {
    add(p.date, p.employee, p.createdAt);
    byDate.get(p.date)?.pins.push(p);
  }
  for (const l of logs) add(l.effectiveDate, l.employee, l.createdAt);
  for (const r of rests) add(r.effectiveDate, r.employee, r.createdAt);

  const ids = [...new Set([...byDate.values()].flatMap((e) => [...e.employees]))];
  const positionOf = new Map((await Employee.find({ _id: { $in: ids } }, 'position')).map((e) => [String(e._id), e.position ? String(e.position) : null]));
  const recordedOn = (date) => records.filter((r) => r.effectiveDate === date);

  const found = [];
  for (const [date, entry] of byDate) {
    const sameDay = recordedOn(date);
    const theirMovers = new Set(sameDay.flatMap((r) => (r.movers ?? []).map((m) => String(m.employee))));
    const theirPositions = new Set(sameDay.flatMap((r) => [String(r.positionA), String(r.positionB)]));
    const counts = new Map();
    for (const id of entry.employees) {
      const position = positionOf.get(id);
      if (!position || theirMovers.has(id) || theirPositions.has(position)) continue;
      counts.set(position, (counts.get(position) ?? 0) + 1);
    }
    const ranked = [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

    const votes = new Map();
    for (const pin of entry.pins) {
      const id = String(pin.employee);
      const now = positionOf.get(id);
      const was = pin.position ? String(pin.position) : null;
      if (!now || !was || now === was || theirMovers.has(id) || theirPositions.has(now) || theirPositions.has(was)) continue;
      const key = [was, now].sort().join('|');
      votes.set(key, (votes.get(key) ?? 0) + 1);
    }
    let pair;
    let ambiguous;
    if (votes.size) {
      const byVotes = [...votes].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
      pair = byVotes[0][0].split('|');
      ambiguous = byVotes.length > 1 && byVotes[1][1] === byVotes[0][1];
    } else {
      if (ranked.length < 2) continue;
      pair = [ranked[0][0], ranked[1][0]].sort();
      ambiguous = ranked.length > 2 && ranked[2][1] === ranked[1][1];
    }
    found.push({
      effectiveDate: date,
      positionA: pair[0],
      positionB: pair[1],
      people: (counts.get(pair[0]) ?? 0) + (counts.get(pair[1]) ?? 0),
      firstAt: entry.firstAt,
      ambiguous,
      positions: ranked.map(([id, count]) => ({ id, count })),
    });
  }
  return found.sort((a, b) => b.effectiveDate.localeCompare(a.effectiveDate));
}

// Undoes an applied swap as if it never happened, from its own date on — for a
// swap set wrong while everyone kept working their old shifts. Each mover goes
// back to their old position with the regular shift they had, the swap day's
// automatic pins and the swap's own rest-day change on that day go, the two
// positions' heads swap back, and their attendance from that day on is judged
// again by the old schedule. Someone moved again since (no longer where the swap
// put them) is left alone and counted, and so is a later rest-day plan the swap
// had to adjust, since what it was before isn't kept.
async function revertPositionSwap(swap, now = new Date()) {
  const date = swap.effectiveDate;
  const positionA = String(swap.positionA);
  const positionB = String(swap.positionB);
  // What the swap did, read while it's still in place, so it can still be shown
  // once undone.
  const movers = await describeSwapPeople(date, swap.movers?.length ? swap.movers : await findMoversOf(swap));
  await ScheduledPositionSwap.updateOne({ _id: swap._id }, { movers });
  const employees = await Employee.find({ _id: { $in: movers.map((m) => m.employee) } });
  const byId = new Map(employees.map((e) => [String(e._id), e]));

  const reverted = [];
  const backFrom = { A: 0, B: 0 };
  let skipped = 0;
  for (const mover of movers) {
    const employee = byId.get(String(mover.employee));
    const back = mover.from === 'A' ? positionA : positionB;
    const swappedInto = mover.from === 'A' ? positionB : positionA;
    if (!employee || String(employee.position) !== swappedInto) {
      skipped += 1;
      continue;
    }
    const update = { position: back };
    // eslint-disable-next-line no-await-in-loop
    const log = await ShiftChangeLog.findOne({ employee: employee._id, effectiveDate: date, source: 'position-swap' });
    if (log) {
      const before = log.previous ?? {};
      update.defaultShiftCategory = before.category ?? null;
      update.defaultShiftStart = before.category ? null : before.startTime ?? null;
      update.defaultShiftEnd = before.category ? null : before.endTime ?? null;
      // eslint-disable-next-line no-await-in-loop
      await log.deleteOne();
    }
    // eslint-disable-next-line no-await-in-loop
    await Employee.updateOne({ _id: employee._id }, update);
    reverted.push(employee._id);
    backFrom[mover.from] += 1;
  }
  if (!reverted.length) return { reverted: 0, skipped, laterRestPlans: 0, backFrom };

  await Shift.deleteMany({ employee: { $in: reverted }, date, note: { $regex: `^${AUTO_SWAP_PIN_NOTE_PREFIX}` } });

  const restRows = await RestDayHistory.find({ employee: { $in: reverted }, effectiveDate: date, source: 'position-swap' });
  for (const row of restRows) {
    // eslint-disable-next-line no-await-in-loop
    await removeRestDayChange(row, now);
    // eslint-disable-next-line no-await-in-loop
    await recomputeLeavesAfterRestChange(row.employee, date);
  }
  const laterRestPlans = await RestDayHistory.countDocuments({
    employee: { $in: reverted },
    effectiveDate: { $gt: date },
    source: 'position-swap',
    changedByEmail: SWAP_REST_DAY_EMAIL,
  });

  const [headA, headB] = await Promise.all([Position.findById(positionA, 'head'), Position.findById(positionB, 'head')]);
  await Promise.all([
    Position.updateOne({ _id: positionA }, { head: headB?.head || null }),
    Position.updateOne({ _id: positionB }, { head: headA?.head || null }),
  ]);

  // Every day since, judged again. A no-show the sweep guessed on a day that is
  // no longer a work day goes; the sweep then marks the days that now are.
  const today = toDateKey(now);
  await AttendanceDaily.deleteMany({
    employee: { $in: reverted },
    date: { $gte: date },
    status: 'absent',
    firstIn: null,
    lastOut: null,
    disciplinaryNote: null,
    autoFilledReason: null,
  });
  for (let day = addDays(date, -1); day <= today; day = addDays(day, 1)) {
    for (const id of reverted) {
      // eslint-disable-next-line no-await-in-loop
      await rejudgeAroundDay(id, day);
    }
  }
  await markAbsentForMissedScans({ fromDate: date, employeeIds: reverted });

  return { reverted: reverted.length, skipped, laterRestPlans, backFrom };
}

// Marks a still-pending swap as applied in one atomic step and returns it —
// or null when it isn't pending any more. Whoever gets it back is the only
// one that runs it: applying the same swap twice moves everyone straight back
// (membership is re-read each time), and two checks can easily overlap — the
// timer, a page load (GET /position-swaps), a second server on the same
// database. Used before applyPositionSwap everywhere a pending swap fires.
async function claimPendingSwap(id, extra = {}) {
  return ScheduledPositionSwap.findOneAndUpdate(
    { _id: id, status: 'pending' },
    { ...extra, status: 'applied', appliedAt: new Date() },
    { new: true }
  );
}

// Runs a claimed swap; if it fails it goes back to pending (as before the
// claim existed) so the next check tries again.
async function runClaimedSwap(swap) {
  try {
    const { movedFromA, movedFromB, movers } = await applyPositionSwap(swap.positionA, swap.positionB, swap.effectiveDate);
    swap.movedFromA = movedFromA;
    swap.movedFromB = movedFromB;
    swap.movers = movers;
    await swap.save();
    return swap;
  } catch (err) {
    await ScheduledPositionSwap.updateOne({ _id: swap._id }, { status: 'pending', $unset: { appliedAt: 1 } });
    throw err;
  }
}

// Applies every pending scheduled swap whose effective date has arrived.
// Called on server startup (catches anything due while the server was down)
// and on a recurring timer — this app has no other background job runner, so
// a plain interval is the simplest thing that reliably fires a swap on a
// future date without needing the browser open.
async function runDueScheduledSwaps() {
  const todayKey = toDateKey(new Date());
  const due = await ScheduledPositionSwap.find({ status: 'pending', effectiveDate: { $lte: todayKey } }, '_id');
  let applied = 0;
  for (const { _id } of due) {
    // eslint-disable-next-line no-await-in-loop
    const swap = await claimPendingSwap(_id);
    if (!swap) continue; // another check already took it
    // eslint-disable-next-line no-await-in-loop
    await runClaimedSwap(swap);
    applied += 1;
  }
  return applied;
}

// ສະຫຼັບກະ's detail of one swap: who it moves (or moved) and from which side,
// their regular shift before and after, what they have on the swap date itself
// and their rest day. A pending one is a preview — whoever is in each position
// right now, worked out the way applyPositionSwap would; who actually moves is
// only settled on the day.
async function swapDetails(swap) {
  const date = swap.effectiveDate;
  let people = [];
  if (swap.status === 'pending') {
    const [positionA, positionB, listA, listB] = await Promise.all([
      Position.findById(swap.positionA),
      Position.findById(swap.positionB),
      Employee.find({ position: swap.positionA, status: 'active' }).sort('employeeCode'),
      Employee.find({ position: swap.positionB, status: 'active' }).sort('employeeCode'),
    ]);
    const canonicalA = canonicalTimeOf(listA);
    const canonicalB = canonicalTimeOf(listB);
    const asFields = (c) => ({ defaultShiftCategory: c.categoryId, defaultShiftStart: c.start, defaultShiftEnd: c.end });
    const [oldTimeA, oldTimeB, nextForA, nextForB] = await Promise.all([
      resolveCanonicalTime(canonicalA),
      resolveCanonicalTime(canonicalB),
      snapshotShift(asFields(canonicalB)),
      snapshotShift(asFields(canonicalA)),
    ]);
    let workThrough = null;
    if (tilesFullDay(oldTimeA, oldTimeB)) {
      const aIsEarly = oldTimeA.startTime < oldTimeB.startTime;
      const startTime = (aIsEarly ? oldTimeA : oldTimeB).startTime;
      const lateEnd = (aIsEarly ? oldTimeB : oldTimeA).endTime;
      workThrough = { from: aIsEarly ? 'A' : 'B', startTime, endTime: lateEnd === startTime ? oneMinuteBefore(startTime) : lateEnd };
    }
    const already = await Shift.find({ employee: { $in: [...listA, ...listB].map((e) => e._id) }, date }).lean();
    const setByHand = new Map(already.filter((s) => !isAutoGeneratedSwapPin(s)).map((s) => [String(s.employee), s]));
    const preview = async (e, from) => {
      const [previous, restBefore] = await Promise.all([snapshotShift(e), restDaysOnFor(e._id, date)]);
      const allowed = restDayAllowedIn(e, from === 'A' ? positionB : positionA);
      let swapDay;
      if (setByHand.has(String(e._id))) swapDay = swapDayOf(setByHand.get(String(e._id)));
      else if (workThrough) {
        swapDay = workThrough.from === from ? { kind: 'extended', status: 'scheduled', startTime: workThrough.startTime, endTime: workThrough.endTime } : { kind: 'off', status: 'swapped' };
      } else if (previous.startTime && previous.endTime) {
        swapDay = { kind: 'kept', status: 'scheduled', startTime: previous.startTime, endTime: previous.endTime };
      }
      return {
        employee: e._id,
        from,
        previous,
        next: from === 'A' ? nextForA : nextForB,
        swapDay,
        restDay: { before: restBefore, after: restBefore.length ? allowed(restBefore) : restBefore },
      };
    };
    people = await Promise.all([...listA.map((e) => preview(e, 'A')), ...listB.map((e) => preview(e, 'B'))]);
  } else if (swap.status === 'applied' || swap.status === 'reverted') {
    const movers = swap.movers?.length ? swap.movers : swap.status === 'applied' ? await findMoversOf(swap) : [];
    people = await describeSwapPeople(date, movers);
    // Still in place with no rest-day change of its own: it didn't change.
    if (swap.status === 'applied') {
      people = await Promise.all(
        people.map(async (p) => {
          if (p.restDay) return p;
          const days = await restDaysOnFor(p.employee, date);
          return { ...p, restDay: { before: days, after: days } };
        })
      );
    }
  }

  const ids = people.map((p) => p.employee);
  const categoryIds = people.flatMap((p) => [p.previous?.category, p.next?.category]).filter(Boolean);
  const [employees, categories] = await Promise.all([
    Employee.find({ _id: { $in: ids } }, 'employeeCode firstName lastName nameEn position status').populate('position', 'name').lean(),
    ShiftCategory.find({ _id: { $in: categoryIds } }, 'name').lean(),
  ]);
  const employeeOf = new Map(employees.map((e) => [String(e._id), e]));
  const categoryName = new Map(categories.map((c) => [String(c._id), c.name]));
  const named = (s) => (s ? { ...s, categoryName: s.category ? categoryName.get(String(s.category)) ?? null : null } : null);
  return {
    preview: swap.status === 'pending',
    people: people
      .map((p) => ({
        ...p,
        employee: employeeOf.get(String(p.employee)) ?? { _id: p.employee },
        previous: named(p.previous),
        next: named(p.next),
        swapDay: p.swapDay ?? null,
        restDay: p.restDay ?? null,
      }))
      .sort((a, b) => a.from.localeCompare(b.from) || String(a.employee.employeeCode ?? '').localeCompare(String(b.employee.employeeCode ?? ''), undefined, { numeric: true })),
  };
}

